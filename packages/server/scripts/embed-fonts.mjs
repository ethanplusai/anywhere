// Writes src/web/fonts.generated.ts from assets/fonts, so the web pages can serve the Geist fonts
// (SIL Open Font License 1.1, see assets/fonts) from memory, with no file paths to resolve after
// bundling. Run it after changing a font file; the generated module is committed.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const font = (name) => readFileSync(join(here, "../assets/fonts", name)).toString("base64");
const out = `// Generated by scripts/embed-fonts.mjs from assets/fonts. Do not edit.
export const GEIST_WOFF2 = "${font("geist.woff2")}";
export const GEIST_MONO_WOFF2 = "${font("geist-mono.woff2")}";
`;
writeFileSync(join(here, "../src/web/fonts.generated.ts"), out);
