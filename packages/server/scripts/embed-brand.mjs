// Writes src/web/brand.generated.ts from assets/brand, so the server can serve its icon (browser tabs)
// and the mark its emails show from memory, with no file paths to resolve after bundling. Run it after
// changing a file in assets/brand; the generated module is committed.
//
// assets/brand/mark.svg is the source. mark-96.png is it at 96px on a transparent background (emails
// show it at 24px, sharp on high-density screens); logo-512.png is the square logo for OAuth consent
// screens such as GitHub's. Both PNGs are rendered from the SVG with a headless browser.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const file = (name) => readFileSync(join(here, "../assets/brand", name));
const out = `// Generated by scripts/embed-brand.mjs from assets/brand. Do not edit.
export const MARK_SVG = ${JSON.stringify(file("mark.svg").toString("utf8").trim())};
export const MARK_PNG = "${file("mark-96.png").toString("base64")}";
`;
writeFileSync(join(here, "../src/web/brand.generated.ts"), out);
