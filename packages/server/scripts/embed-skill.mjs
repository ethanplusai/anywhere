/* global console */
// Writes src/web/skill.generated.ts from skill/anywhere, so the app can hand new users the skill as a
// download (GET /skill/anywhere.tar.gz) without them cloning this repository. Run it after
// `node skill/build.mjs`; the generated module is committed and CI checks it is current.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../../../skill/anywhere");
const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else files.push({ path: `anywhere/${relative(root, full)}`, content: readFileSync(full, "utf8") });
  }
};
walk(root);
writeFileSync(
  join(here, "../src/web/skill.generated.ts"),
  `// Generated by scripts/embed-skill.mjs from skill/anywhere. Do not edit.\nexport const SKILL_FILES: { path: string; content: string }[] = ${JSON.stringify(files, null, 2)};\n`,
);
console.log(`embedded ${files.length} skill files`);
